/** Seven calendar-day datasets. UTC calendar dates; no automatic time-zone conversions. */
export const STUDY_DATES: readonly string[] = Object.freeze(
  Array.from({ length: 7 }, (_, index) => `2023-06-${String(index + 1).padStart(2, '0')}`)
);

/**
 * Source contract for incoming files:
 *   data/daily/2023-06-01.csv ... data/daily/2023-06-07.csv
 * Existing hotspot parser requires longitude,latitude,radius_km columns.
 */
export function dailyCsvPath(date: string): string {
  if (!STUDY_DATES.includes(date)) throw new Error('Date outside study window');
  return `./data/daily/${date}.csv`;
}

export interface HotspotRecord {
  longitude: number;
  latitude: number;
  radius_km: number;
}

/** Coarse geographic extent filter; exact national border clipping needs a polygon. */
export function inCanadaExtent(record: HotspotRecord): boolean {
  return (
    record.latitude >= 41.5 &&
    record.latitude <= 84 &&
    record.longitude >= -141.5 &&
    record.longitude <= -52
  );
}

