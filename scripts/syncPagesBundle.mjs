import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const distDir = path.join(rootDir, 'dist');
const distIndex = path.join(distDir, 'index.html');
const distAssets = path.join(distDir, 'assets');
const rootAssets = path.join(rootDir, 'assets');

if (!fs.existsSync(distIndex) || !fs.existsSync(distAssets)) {
  console.warn('[syncPagesBundle] dist/ not found; skipping static bundle sync.');
  process.exit(0);
}

const html = fs.readFileSync(distIndex, 'utf-8');
const jsMatch = html.match(/src="(?:\.\/|\/[^"]*\/)?assets\/(index-[^"]+\.js)"/);
const cssMatch = html.match(/href="(?:\.\/|\/[^"]*\/)?assets\/(index-[^"]+\.css)"/);

if (!jsMatch) {
  console.warn('[syncPagesBundle] Could not locate compiled entry JS in dist/index.html');
  process.exit(0);
}

const entryJs = jsMatch[1];
const entryCss = cssMatch ? cssMatch[1] : null;

// Copy dist/assets/* into ./assets/ at repository root for branch-based GitHub Pages (dev / site-*)
fs.rmSync(rootAssets, { recursive: true, force: true });
fs.mkdirSync(rootAssets, { recursive: true });
for (const file of fs.readdirSync(distAssets)) {
  const srcPath = path.join(distAssets, file);
  if (fs.statSync(srcPath).isFile()) {
    fs.copyFileSync(srcPath, path.join(rootAssets, file));
  }
}

// Create ./pages-loader.js at repository root
const loaderLines = [
  '// Auto-generated by scripts/syncPagesBundle.mjs',
  '// Boots the compiled FireLedger bundle when GitHub Pages serves the raw dev/feature branch.',
];
if (entryCss) {
  loaderLines.push(
    `const link = document.createElement('link');`,
    `link.rel = 'stylesheet';`,
    `link.href = new URL('./assets/${entryCss}', import.meta.url).href;`,
    `document.head.appendChild(link);`
  );
}
loaderLines.push(`import('./assets/${entryJs}');`, '');

fs.writeFileSync(path.join(rootDir, 'pages-loader.js'), loaderLines.join('\n'), 'utf-8');

// Ensure .nojekyll and 404.html exist in both dist/ and repository root
fs.writeFileSync(path.join(distDir, '.nojekyll'), '', 'utf-8');
fs.copyFileSync(distIndex, path.join(distDir, '404.html'));
fs.writeFileSync(path.join(rootDir, '.nojekyll'), '', 'utf-8');
fs.copyFileSync(path.join(rootDir, 'index.html'), path.join(rootDir, '404.html'));

console.log(
  `[syncPagesBundle] Synced ./assets/${entryJs}${entryCss ? ` + ./assets/${entryCss}` : ''} and ./pages-loader.js for branch-based GitHub Pages.`
);
